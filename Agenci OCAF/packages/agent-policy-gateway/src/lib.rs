//! Native candidate package for agent-policy-gateway.
pub mod zenoh;
use ocaf_import_core::{AgentProfile, TaskDraft, evolution::{Candidate, Evaluation, SearchReport}};
pub const PROFILE: AgentProfile = AgentProfile {
    id: r#"OCAF-AGENT-EXT-agent-policy-gateway"#, source_id: r#"agent-policy-gateway"#, name: r#"Agent Policy Gateway"#,
    specialization: r#"Portfolio domain agent — planning/reasoning core."#, source_ref: r#"https://github.com/mojealterego/Ageni-AI-mojealterego/blob/a86626db5f40630809ecbb4c4110a3774ff16150/agents/portfolio_agent.py"#,
    instructions: r#"Decide ALLOW, REVIEW or DENY for proposed agent actions; evaluate workload identity, capability scope, data sensitivity, policy conflict, approval, budget, rate and postcondition requirements; fail closed on missing evidence."#,
};
pub fn profile() -> AgentProfile { PROFILE }
pub fn prepare(tenant: &str, request: &str, input: &str) -> Result<TaskDraft, &'static str> {
    ocaf_import_core::prepare(&PROFILE, tenant, request, input)
}
pub fn evolve<P,E>(rounds: u32, propose: P, evaluate: E) -> Result<SearchReport, String>
where P: FnMut(&Candidate,u32)->Result<String,String>, E: FnMut(&Candidate)->Result<Evaluation,String> {
    ocaf_import_core::evolution::search(&PROFILE, rounds, propose, evaluate)
}
