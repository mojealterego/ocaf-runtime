//! Native candidate package for supply-chain.
pub mod zenoh;
use ocaf_import_core::{AgentProfile, TaskDraft, evolution::{Candidate, Evaluation, SearchReport}};
pub const PROFILE: AgentProfile = AgentProfile {
    id: r#"OCAF-AGENT-EXT-supply-chain"#, source_id: r#"supply-chain"#, name: r#"Supply Chain Orchestrator Agent"#,
    specialization: r#"Supply disruption analysis, inventory impact and scenario planning."#, source_ref: r#"https://github.com/mojealterego/Ageni-AI-mojealterego/blob/a86626db5f40630809ecbb4c4110a3774ff16150/agents/occupational-ai/agent.py"#,
    instructions: r#"Supply Chain
Assess disruption evidence, map affected shipments/materials, estimate time-to-impact from supplied inventory and compare wait, reroute and expedite scenarios.
Show assumptions and cost units; do not invent shipment or inventory data.
No booking, rerouting or purchase order without approval within configured authority."#,
};
pub fn profile() -> AgentProfile { PROFILE }
pub fn prepare(tenant: &str, request: &str, input: &str) -> Result<TaskDraft, &'static str> {
    ocaf_import_core::prepare(&PROFILE, tenant, request, input)
}
pub fn evolve<P,E>(rounds: u32, propose: P, evaluate: E) -> Result<SearchReport, String>
where P: FnMut(&Candidate,u32)->Result<String,String>, E: FnMut(&Candidate)->Result<Evaluation,String> {
    ocaf_import_core::evolution::search(&PROFILE, rounds, propose, evaluate)
}
